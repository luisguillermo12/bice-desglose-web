  CREATE OR REPLACE FORCE VIEW "CIF_VIEW_CLIENTES_ONLINE" ("NUM_IDEN", "COD_TIPO_IDEN", "NOMBRES", "PATERNO", "MATERNO", "COD_EJECUTIVO", "GLS_EJECUTIVO", "GLS_SECTORCORTA", "GLS_SECTORLARGA", "COD_SUCURSAL", "GLOSA_SUC", "NUM_ROL_EMPLEADO", "NUM_CARPETA", "COD_TIPO_CLIENTE", "GLS_TIPCLIEN_CORTA", "GLS_TIPCLIEN_LARGA", "COD_ESTA_DEUD", "GLS_ESTDEU_CORTA", "GLS_ESTDEU_LARGA", "COD_CLAS_SUPER", "GLS_CLASSEGMEN_CORTA", "COD_CLAS_SEG", "FEC_CLASIF", "COD_SECTOR", "COD_CLIENTE", "FLG_EXCL_BARRIDO", "COMPLETO", "NOMBRE", "COD_TIPO_ALERTA", "FEC_ALERTA", "GLS_RAZON_SOCIAL_LEGAL", "GLS_SINO_SBIF", "COD_ALERTA_FRD", "GLS_ALERTA_FRDCORTA", "GLS_ALERTALARGA_FRD") AS 
  SELECT
 IDECLI.NUM_IDEN,
 IDECLI.COD_TIPO_IDEN,
 NVL(CLIJUR.GLS_RAZON_SOCI || CLINAT.NOM_NOMBRES, ' ') NOMBRES,
 NVL(CLINAT.NOM_PATERNO, ' ') PATERNO,
 NVL(CLINAT.NOM_MATERNO, ' ') MATERNO,
 NVL(EJECUT.COD_EJECUTIVO, -1) COD_EJECUTIVO,
 NVL(EJECUT.GLS_EJECUTIVO, ' ') GLS_EJECUTIVO,
 NVL(DESCOD2.GLS_GENERICACORTA,' ') GLS_SECTORCORTA,
 NVL(DESCOD2.GLS_GENERICALARGA,' ') GLS_SECTORLARGA,
 DECODE(EJECTA.COD_SUCURSAL,NULL,NVL(BASCLI.COD_SUCURSAL,0), EJECTA.COD_SUCURSAL) COD_SUCURSAL,
 DECODE(SUCEJEC.GLS_DESCRIPCION,NULL,NVL(SUCURS.GLS_DESCRIPCION, ' '), SUCEJEC.GLS_DESCRIPCION) GLOSA_SUC,
 BASCLI.NUM_ROL_EMPLEADO NUM_ROL_EMPLEADO,
 NVL(BASCLI.NUM_CARPETA, 0) NUM_CARPETA,
 NVL(BASCLI.COD_TIPO_CLIENTE, 0) COD_TIPO_CLIENTE,
 NVL(DESCOD.GLS_GENERICALARGA, ' ') GLS_TIPCLIEN_CORTA,
 NVL(DESCOD.GLS_GENERICACORTA, ' ') GLS_TIPCLIEN_LARGA,
 NVL(BASCLI.COD_ESTA_DEUD, 0) COD_ESTA_DEUD,
 NVL(DESCOD1.GLS_GENERICALARGA, ' ') GLS_ESTDEU_CORTA,
 NVL(DESCOD1.GLS_GENERICACORTA, ' ') GLS_ESTDEU_LARGA,
 NVL(CLARIE.COD_CLARIE, 'SIN INF') COD_CLAS_SUPER,
 NVL(DESCOD3.GLS_GENERICACORTA, 'SIN INF.') GLS_CLASSEGMEN_CORTA,
 NVL(CLASEG.COD_CLAS_SEG, 'SIN INF.') COD_CLAS_SEG,
 CLARIE.FEC_CLARIE FEC_CLASIF,
 NVL(BASCLI.COD_SECTOR, -1) COD_SECTOR,
 NVL(BASCLI.COD_CLIENTE, ' ') COD_CLIENTE,
 NVL(AGRUPACION.COD_GRUPO1, ' ') FLG_EXCL_BARRIDO,
 trim(CLINAT.NOM_PATERNO)||DECODE(trim(CLINAT.NOM_PATERNO),'','',' ')||trim(CLINAT.NOM_MATERNO)||DECODE(trim(CLINAT.NOM_MATERNO),'','',' ')||trim(CLIJUR.GLS_RAZON_SOCI)||DECODE(trim(CLIJUR.GLS_RAZON_SOCI),'','',' ')||trim(CLINAT.NOM_NOMBRES) COMPLETO,
 substr(trim(concat(concat(trim(NVL(CLINAT.NOM_PATERNO, ' ')),' '),
        concat(concat(trim(NVL(CLINAT.NOM_MATERNO, ' ')),DECODE(trim(CLINAT.NOM_MATERNO),'','',' ')) ,
        NVL(trim(CLIJUR.GLS_RAZON_SOCI) || TRIM(CLINAT.NOM_NOMBRES), ' ') ))),1,40) NOMBRE,
 NVL(BASCLI.COD_TIPO_ALERTA, '') COD_TIPO_ALERTA,
 BASCLI.FEC_ALERTA FEC_ALERTA,
 NVL(CLIJUR.GLS_RAZON_SOCIAL_LEGAL, ' ') GLS_RAZON_SOCIAL_LEGAL,
 -- NVL(BASCLI.GLS_SINO_SBIF, DECODE(BASCLI.COD_SECTOR, 121, trim(CLINAT.NOM_PATERNO)||' '|| trim(CLINAT.NOM_MATERNO)|| ' ' || trim(CLINAT.NOM_NOMBRES), trim(CLIJUR.GLS_RAZON_SOCI))) GLS_SINO_SBIF
 NVL(BASCLI.GLS_SINO_SBIF,'' ) GLS_SINO_SBIF,
 NVL(BASCLI.COD_ALERTA_FRD, '') COD_ALERTA_FRD,
 NVL(TFRAUDE.GLS_GENERICACORTA, '') GLS_ALERTA_FRDCORTA,
 NVL(TFRAUDE.GLS_GENERICALARGA, '') GLS_ALERTA_FRDLARGA
FROM
 (SELECT * FROM DESCOD WHERE COD_TABLA='CLNSEGM' AND COD_REG_STATUS=0) DESCOD3,
 (SELECT * FROM DESCOD WHERE COD_TABLA='ORISEC' AND COD_REG_STATUS=0) DESCOD2,
 (SELECT * FROM DESCOD WHERE COD_TABLA='ESTDEU' AND COD_REG_STATUS=0) DESCOD1,
 (SELECT * FROM DESCOD WHERE COD_TABLA='CLNBICE' AND COD_REG_STATUS=0) DESCOD,
 (SELECT * FROM DESCOD WHERE COD_TABLA='TFRAUDE' AND COD_REG_STATUS=0) TFRAUDE,
 EJECTA,
 EJECTA EJECUT,
 CLASEG,
 CLARIE,
 BASCLI,
 CLIJUR,
 CLINAT,
 IDECLI,
 SUCURS,
 AGRUPACION,
 SUCURS SUCEJEC
WHERE
 BASCLI.COD_REG_STATUS=0
 AND (AGRUPACION.NUM_CLIENTE(+)=BASCLI.NUM_CLIENTE AND
      AGRUPACION.COD_REG_STATUS(+)=0)
 AND (IDECLI.NUM_CLIENTE=BASCLI.NUM_CLIENTE AND IDECLI.COD_REG_STATUS=0)
 AND (CLASEG.NUM_CLIENTE(+)=BASCLI.NUM_CLIENTE AND CLASEG.COD_REG_STATUS(+)=0)
 AND (CLARIE.NUM_CLIENTE(+)=BASCLI.NUM_CLIENTE AND CLARIE.COD_TIPCLARIE(+)='CLSUPER' AND CLARIE.COD_REG_STATUS(+)=0)
 AND (CLINAT.NUM_CLIENTE(+)=BASCLI.NUM_CLIENTE AND CLINAT.COD_REG_STATUS(+)=0)
 AND (CLIJUR.NUM_CLIENTE(+)=BASCLI.NUM_CLIENTE AND CLIJUR.COD_REG_STATUS(+)=0)
 AND (SUCURS.COD_SUCURSAL(+)=BASCLI.COD_SUCURSAL AND SUCURS.COD_REG_STATUS(+)=0)
 AND (SUCEJEC.COD_SUCURSAL(+)=EJECTA.COD_SUCURSAL AND SUCEJEC.COD_REG_STATUS(+)=0)
 AND (EJECTA.NUM_ROLEMPLEADO(+)=BASCLI.NUM_ROL_EMPLEADO AND EJECTA.cod_reg_status(+)=0 AND EJECTA.cod_grupo_trab(+) <> 26 and EJECTA.cod_grupo_trab(+) <> 31 )
 AND (EJECUT.NUM_ROLEMPLEADO=BASCLI.NUM_ROL_EMPLEADO AND EJECUT.cod_reg_status(+)=0 AND EJECUT.COD_EJECUTIVO=(SELECT A.COD_EJECUTIVO FROM EJECTA A WHERE A.NUM_ROLEMPLEADO=BASCLI.NUM_ROL_EMPLEADO AND A.COD_REG_STATUS=0 AND ROWNUM < 2) )
 AND (DESCOD.COD_GENERICO(+)=BASCLI.COD_TIPO_CLIENTE )
 AND (DESCOD1.COD_GENERICO(+)=BASCLI.COD_ESTA_DEUD )
 AND (DESCOD2.COD_GENERICO(+)=BASCLI.COD_SECTOR )
 AND (DESCOD3.COD_GENERICO(+)=CLASEG.COD_CLAS_SEG)
 AND (TFRAUDE.COD_GENERICO(+)=BASCLI.COD_ALERTA_FRD )
 
 
 
