      ,CT.COD_CONCEPTO COD_PADRE
      ,DECODE(INSTR(CT.COD_CONCEPTO,'.'),0,'(' || CT.COD_CONCEPTO || ')','') COD_CONCEPTO
      ,DECODE(CT.COD_TIPO_REGIS,'MULTIREGISTRO',CT.GLS_CONCEPTO2,CT.GLS_CONCEPTO) GLS_CONCEPTO
      ,CT.DEC_PRINT NUM_DEC_PRINT
FROM  (SELECT DISTINCT C.COD_TIPO_CONCEP
             ,C.COR_CONCEPTO
             ,C.NUM_SECUENCIA
             ,V.COR_VALOR
             ,C.COD_CONCEPTO
             ,C.COD_TIPO_REGIS
             ,C.GLS_CONCEPTO
			 ,V.GLS_CONCEPTO GLS_CONCEPTO2
             ,C.FLG_IS_TOTAL
             ,C.FLG_CON_ACTIVO
             ,NVL(C.NUM_DEC_PRINT,0) DEC_PRINT
       FROM   CONCEP C
             ,VALPRD V
       WHERE  C.FLG_CON_ACTIVO = 1
       AND    C.FLG_IS_TOTAL = 1
       AND    V.COD_TIPO_CONCEP (+)= C.COD_TIPO_CONCEP
       AND    V.COR_CONCEPTO (+)= C.COR_CONCEPTO
       AND    V.COD_CLIENTE (+)= :codCliente
       AND    V.COD_TIPO_DES (+)= :codTipoDes
       AND    V.COD_SUBTIPO_DES (+)= :codSubTipoDes
       AND    V.COD_MONEDA (+)= :codMonedaDes) CT
      ,CONIMP CI
WHERE  CI.COD_CLIENTE = :codCliente
AND    CI.COD_TIPO_DES = :codTipoDes
AND    CI.COD_SUBTIPO_DES = :codSubTipoDes
AND    CI.COD_MONEDA = :codMonedaDes
AND    CI.COD_TIPO_CONCEP = CT.COD_TIPO_CONCEP
AND    CI.COR_CONCEPTO = CT.COR_CONCEPTO
----------------------
ORDER BY CT.COD_TIPO_CONCEP, CT.NUM_SECUENCIA, CT.COR_VALOR ASC


