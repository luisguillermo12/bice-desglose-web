SELECT * from (

SELECT I.NUM_IDEN NUM_IDEN, NULL as CODIGO_CLIENTE, C.GLS_RAZON_SOCI NOMBRE, B.COD_SECTOR_ECONOM COD_SECTOR_ECONOM
            FROM IDECLI I, CLIJUR C, BASCLI B
           WHERE UPPER(C.GLS_RAZON_SOCI) LIKE UPPER('%60556%')
             AND I.COD_REG_STATUS = 0
             AND C.COD_REG_STATUS = 0
             AND C.NUM_CLIENTE = I.NUM_CLIENTE
             AND B.COD_REG_STATUS (+)= 0
             AND B.NUM_CLIENTE (+)= I.NUM_CLIENTE
           
           union

SELECT I.NUM_IDEN NUM_IDEN, NULL as CODIGO_CLIENTE, C.NOM_NOMBRES || ' ' || C.NOM_PATERNO || ' ' || C.NOM_MATERNO NOMBRE, NULL COD_SECTOR_ECONOM
            FROM IDECLI I, CLINAT C
           WHERE I.COD_REG_STATUS = 0
             AND UPPER(C.NOM_NOMBRES || ' ' || C.NOM_PATERNO || ' ' || C.NOM_MATERNO) LIKE UPPER('%76225817K%')
             AND C.NUM_CLIENTE = I.NUM_CLIENTE
             AND C.COD_REG_STATUS = 0

union 
SELECT NULL as NUM_IDEN, COD_CLIENTE CODIGO_CLIENTE,
                 NOM_CLIENTE || DECODE(' ' || NOM_PATERNO,' ','',' ' || NOM_PATERNO) || DECODE(' ' || NOM_MATERNO,' ','',' ' || NOM_MATERNO) NOMBRE,
                 TO_NUMBER(COD_ACTIVIDAD) COD_SECTOR_ECONOM
            FROM SINRUT
           WHERE UPPER(NOM_CLIENTE || ' ' || NOM_PATERNO || ' ' || NOM_MATERNO) LIKE UPPER('%EMPRESA NERUDA 11%')
) ORDER BY NOMBRE ASC  ;

