-- sub-sector
SELECT DISTINCT NVL(A.COD_GENERICO,'-1') COD_SECTOR, NVL(B.COD_GENERICO,'-1') COD_SUBSECTOR, NVL(B.GLS_GENERICALARGA,' ') GLS_SUBSECTOR
FROM DESCOD A, DESCOD B, DESCOD C, RELTAB AB, RELTAB BC
WHERE C.COD_TABLA = 'CLAECONO' AND C.COD_REG_STATUS = 0 AND B.COD_TABLA (+) = 'SUBSECON' AND B.COD_REG_STATUS (+) = 0
    AND A.COD_TABLA (+) = 'SECECONO' AND A.COD_REG_STATUS (+) = 0 AND BC.COD_TABLA1 (+) = 'SUBSECON' AND BC.COD_TABLA2 (+) = 'CLAECONO'
    AND BC.COD_REG_STATUS (+) = 0 AND BC.COD_GENERICO2 (+) = C.COD_GENERICO AND AB.COD_TABLA1 (+) = 'SECECONO' AND AB.COD_TABLA2 (+) = 'SUBSECON'
    AND AB.COD_REG_STATUS (+) = 0 AND AB.COD_GENERICO2 (+) = BC.COD_GENERICO1 AND B.COD_GENERICO (+) = BC.COD_GENERICO1 AND A.COD_GENERICO (+) = AB.COD_GENERICO1
ORDER BY GLS_SUBSECTOR ASC;
-- sectores
SELECT DISTINCT NVL(A.COD_GENERICO,'-1') COD_SECTOR, NVL(A.GLS_GENERICALARGA,' ') GLS_SECTOR
FROM DESCOD A, DESCOD B, DESCOD C, RELTAB AB, RELTAB BC
WHERE C.COD_TABLA = 'CLAECONO' AND C.COD_REG_STATUS = 0 AND B.COD_TABLA (+) = 'SUBSECON' AND B.COD_REG_STATUS (+) = 0
    AND A.COD_TABLA (+) = 'SECECONO' AND A.COD_REG_STATUS (+) = 0 AND BC.COD_TABLA1 (+) = 'SUBSECON' AND BC.COD_TABLA2 (+) = 'CLAECONO'
    AND BC.COD_REG_STATUS (+) = 0 AND BC.COD_GENERICO2 (+) = C.COD_GENERICO AND AB.COD_TABLA1 (+) = 'SECECONO' AND AB.COD_TABLA2 (+) = 'SUBSECON'
    AND AB.COD_REG_STATUS (+) = 0 AND AB.COD_GENERICO2 (+) = BC.COD_GENERICO1 AND B.COD_GENERICO (+) = BC.COD_GENERICO1 AND A.COD_GENERICO (+) = AB.COD_GENERICO1
ORDER BY GLS_SECTOR ASC;
