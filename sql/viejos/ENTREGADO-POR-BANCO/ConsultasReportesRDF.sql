FUNCTION FC_NOMBREFormula RETURN VARCHAR2 IS
V_NOMBRE  VARCHAR2(80);
BEGIN
  SELECT GLS_NOMBRE
    INTO V_NOMBRE
    FROM (SELECT DECODE(BS.COD_SECTOR, 121, N.NOM_NOMBRES || ' ' || N.NOM_PATERNO || ' ' || N.NOM_MATERNO, J.GLS_RAZON_SOCI) GLS_NOMBRE
            FROM IDECLI I, BASCLI BS, CLIJUR J, CLINAT N
           WHERE I.NUM_IDEN = :codCliente
             AND I.COD_REG_STATUS = 0
             AND BS.NUM_CLIENTE = I.NUM_CLIENTE
             AND BS.COD_REG_STATUS = 0
             AND J.NUM_CLIENTE (+)= BS.NUM_CLIENTE
             AND J.COD_REG_STATUS (+)= 0
             AND N.NUM_CLIENTE (+)= BS.NUM_CLIENTE
             AND N.COD_REG_STATUS (+)= 0
          UNION
          SELECT DECODE(NOM_PATERNO,NULL,NOM_CLIENTE,NOM_CLIENTE || ' ' || NOM_PATERNO || ' ' || NOM_MATERNO) GLS_NOMBRE
            FROM SINRUT
           WHERE  COD_CLIENTE = :codCliente)
   WHERE ROWNUM < 2; 
	
	RETURN V_NOMBRE;

EXCEPTION
	WHEN NO_DATA_FOUND THEN
    V_NOMBRE := 'SIN NOMBRE';
    RETURN V_NOMBRE;
	WHEN OTHERS THEN
		RETURN sqlerrm;
END;


FUNCTION CF_SECTORFormula RETURN VARCHAR2 IS
	V_SECTOR	VARCHAR2(80);
BEGIN
  SELECT GLS_GENERICALARGA
    INTO V_SECTOR
    FROM (SELECT A.GLS_GENERICALARGA 
            FROM IDECLI I, BASCLI BS, DESCOD A, DESCOD B, DESCOD C, RELTAB AB, RELTAB BC
           WHERE I.NUM_IDEN = :codCliente
             AND    I.COD_REG_STATUS = 0
             AND    BS.NUM_CLIENTE = I.NUM_CLIENTE
             AND    BS.COD_REG_STATUS = 0
             AND    C.COD_TABLA = 'CLAECONO'
             AND    C.COD_GENERICO = BS.COD_SECTOR_ECONOM
             AND    C.COD_REG_STATUS = 0
             AND    B.COD_TABLA (+)= 'SUBSECON'
             AND    B.COD_REG_STATUS (+)= 0
             AND    A.COD_TABLA (+)= 'SECECONO'
             AND    A.COD_REG_STATUS (+)= 0
             AND    BC.COD_TABLA1 (+)= 'SUBSECON'
             AND    BC.COD_TABLA2 (+)= 'CLAECONO'
             AND    BC.COD_REG_STATUS (+)= 0
             AND    BC.COD_GENERICO2 (+)= C.COD_GENERICO
             AND    AB.COD_TABLA1 (+)= 'SECECONO'
             AND    AB.COD_TABLA2 (+)= 'SUBSECON'
             AND    AB.COD_REG_STATUS (+)= 0
             AND    AB.COD_GENERICO2 (+)= BC.COD_GENERICO1
             AND    B.COD_GENERICO (+)= BC.COD_GENERICO1
             AND    A.COD_GENERICO (+)= AB.COD_GENERICO1
          UNION
          SELECT A.GLS_GENERICALARGA
            FROM SINRUT S, DESCOD A, DESCOD B, DESCOD C, RELTAB AB, RELTAB BC
           WHERE S.COD_CLIENTE = :codCliente
             AND C.COD_TABLA = 'CLAECONO'
             AND C.COD_GENERICO = S.COD_ACTIVIDAD
             AND C.COD_REG_STATUS = 0
             AND B.COD_TABLA (+)= 'SUBSECON'
             AND B.COD_REG_STATUS (+)= 0
             AND A.COD_TABLA (+)= 'SECECONO'
             AND A.COD_REG_STATUS (+)= 0
